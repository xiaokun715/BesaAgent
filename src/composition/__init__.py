"""组合根：**唯一**允许 import 全部同仓库模块的地方。

**为什么新增这一层**（对既定目录结构的一处补充）。

原结构把装配分散到 ``apps/cli/runtime/`` ``apps/mcp/runtime/`` ``apps/server/runtime/``。
按字面执行，三个 app 会各写一份「读配置 → 建注册表 → 建网关」——
而这三份会在第一次有人只改其中一份时开始漂移，且症状是
「CLI 里能降级、服务里不能」这类极难归因的行为差异。

这正是 besa-iv-kb《重构文件结构设计》§2.5「**组合根唯一且被两个 app 共享**」
要避免的问题，那边给出的解法就是独立的 ``src/composition/``。本仓库沿用同一结论。

**分工**：

=========================  ====================================================
``src/composition/``       共享装配：配置 → 注册表 → 网关（三个 app 都用）
``apps/*/runtime/``        app 自身运行时：CLI 的命令循环、server 的 lifespan、
                           MCP 的会话管理 —— 它们**调用**组合根，不重复装配
``foundation/container``   连接与实例的持有/释放（PG / Redis 接进来后归它管）
=========================  ====================================================

**依赖方向**：``composition`` 可以 import 任何东西，但**没有任何东西 import 它**。
一旦有模块反过来依赖组合根，装配就从「一个地方」变成「一层」，
优势立刻消失。
"""
